// Independent proof: cross-check every memory the app says it stored against Sui mainnet (read via Tatum),
// then write docs/PROOF.md. Run: npm run verify
import { writeFileSync } from "node:fs";
import { q } from "../lib/db.ts";
import { chainInfo, memwalAccount, ownedBlobs } from "../lib/tatum.ts";
import { memwal } from "../lib/memory.ts";
import { blobIdToU256, walruscan, suiscanObject, suiscanAccount } from "../lib/util.ts";

const t0 = Date.now();
const [ci, acct] = await Promise.all([chainInfo(), memwalAccount()]);
const blobs = await ownedBlobs(acct.owner);
const byId = new Map(blobs.map((b) => [b.blobIdU256, b]));
const stored = await q<any>(`select id, user_id, namespace, kind, blob_id, created_at from memory_jobs where status = 'stored' and blob_id is not null order by id`);
const pending = await q<any>(`select status, count(*)::int n from memory_jobs group by status`);
const ns = await memwal().listNamespaces({ limit: 200 });
const recall = await q<any>(`select count(*)::int n, avg(latency_ms)::int avg, percentile_cont(0.95) within group (order by latency_ms)::int p95, sum(case when ok then 1 else 0 end)::int ok from recall_events`);
const picks = await q<any>(`select arm, count(*)::int n, count(rating)::int rated, avg(case rating when 'loved' then 2 when 'fine' then 1 when 'bailed' then 0 end)::float score from picks group by arm`);
const users = await q<any>(`select count(*)::int n from users where onboard_step = 'done'`);

let matched = 0;
const rows: string[] = [];
for (const m of stored) {
  const c = byId.get(blobIdToU256(m.blob_id));
  if (c) matched++;
  rows.push(`| ${m.id} | ${m.kind} | \`${m.namespace}\` | [${m.blob_id.slice(0, 10)}…](${walruscan(m.blob_id)}) | ${c ? `[${c.objectId.slice(0, 10)}…](${suiscanObject(c.objectId)})` : "**not found**"} | ${c?.endEpoch ?? "–"} | ${new Date(m.created_at).toISOString().slice(0, 16)}Z |`);
}

const md = `# Proof — Pocket Pundit on Walrus Memory (Sui mainnet)

Generated by \`npm run verify\` at ${new Date().toISOString()} in ${((Date.now() - t0) / 1000).toFixed(1)}s.
Every on-chain read below goes through **Tatum's Sui gateway** (native gRPC \`sui.rpc.v2\`).

## Account

| | |
|---|---|
| MemWalAccount | [\`${acct.id}\`](${suiscanObject(acct.id)}) |
| Owner (Sui address) | [\`${acct.owner}\`](${suiscanAccount(acct.owner)}) |
| Active | ${acct.active} |
| Delegate keys | ${acct.delegateKeys.map((k) => `${k.label}: \`${k.publicKeyHex}\``).join("<br>")} |
| Chain (via Tatum gRPC GetServiceInfo) | ${ci.chain}, epoch ${ci.epoch}, checkpoint ${ci.checkpoint} |

## Memory counts

| Source | Count |
|---|---|
| Memories the app recorded as stored (ledger) | ${stored.length} |
| …of which a Walrus \`Blob\` object owned by the account owner exists on Sui | **${matched}** |
| Walrus \`Blob\` objects owned by the owner (all namespaces) | ${blobs.length} |
| Relayer namespaces on this account | ${ns.namespaces.length} (${ns.namespaces.reduce((s: number, n: any) => s + Number(n.memory_count ?? 0), 0)} memories) |
| Write queue states | ${pending.map((p) => `${p.status}: ${p.n}`).join(", ")} |

## Is memory used?

| Metric | Value |
|---|---|
| Users onboarded | ${users[0].n} |
| Recall calls | ${recall[0].n} (ok ${recall[0].ok ?? 0}), avg ${recall[0].avg ?? "–"} ms, p95 ${recall[0].p95 ?? "–"} ms |
| Picks by arm | ${picks.map((p) => `${p.arm}: ${p.n} sent, ${p.rated} rated, mean rating ${p.score === null ? "–" : Number(p.score).toFixed(2)}`).join("<br>")} |

Rating scale: loved = 2, fine = 1, bailed = 0 ("didn't watch" excluded).

## Every stored memory

Namespaces are HMAC-derived so no user id is exposed on-chain. Memory content is Seal-encrypted on Walrus; open a blob on walruscan to see the ciphertext, and the Sui object to see owner, size and \`storage.end_epoch\`.

| # | Kind | Namespace | Blob | Sui object | End epoch | Written |
|---|---|---|---|---|---|---|
${rows.join("\n")}
`;
writeFileSync("docs/PROOF.md", md);
console.log(`PROOF.md written: ${matched}/${stored.length} stored memories found on-chain; ${blobs.length} Blob objects owned.`);
process.exit(0);
